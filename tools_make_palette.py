"""Builds src/p2a_icons.py: per-item colour statistics (average / dark / light / accent) measured from the
vanilla textures. Only these few numbers are kept - no texture pixels - and the app draws its own simplified
tiles from them. Run once; needs Pillow.   usage: python tools_make_palette.py <minecraft-assets>/data/1.21.1"""
import json, os, sys, colorsys
from PIL import Image
ROOT = sys.argv[1]
it = json.load(open(os.path.join(ROOT, "items_textures.json")))
EXCLUDE = {"chest", "ender_chest", "trapped_chest", "beacon", "shield", "skeleton_skull", "wither_skeleton_skull",
           "player_head", "zombie_head", "creeper_head", "dragon_head", "piglin_head", "decorated_pot", "air"}
OVERRIDE = {"grass_block": "grass_block_side", "podzol": "podzol_side", "mycelium": "mycelium_side",
            "crimson_nylium": "crimson_nylium_side", "warped_nylium": "warped_nylium_side",
            "bookshelf": "bookshelf", "crafting_table": "crafting_table_front",
            "cartography_table": "cartography_table_side3", "fletching_table": "fletching_table_front"}
TINT = {"leaves": (0.30, 0.55, 0.20), "grass": (0.36, 0.62, 0.24), "fern": (0.30, 0.55, 0.22), "vine": (0.30, 0.55, 0.22),
        "lily_pad": (0.18, 0.45, 0.20)}
rows = []
for e in it:
    name, t = e["name"], e["texture"]
    if not t or name in EXCLUDE or name.endswith("_banner"):
        continue
    kind, _, nm = t.split(":")[-1].partition("/")
    d = {"item": "items", "items": "items", "block": "blocks", "blocks": "blocks"}.get(kind)
    f = os.path.join(ROOT, d, nm + ".png") if d else None
    if name in OVERRIDE:
        g = os.path.join(ROOT, "blocks", OVERRIDE[name] + ".png")
        if os.path.exists(g):
            f, d = g, "blocks"
    if not f or not os.path.exists(f):
        continue
    im = Image.open(f).convert("RGBA")
    w = min(im.size)
    im = im.crop((0, 0, w, w)).resize((16, 16), Image.BOX)
    px = [p[:3] for p in im.getdata() if p[3] > 128]
    if not px:
        continue
    px.sort(key=lambda p: 0.3 * p[0] + 0.59 * p[1] + 0.11 * p[2])
    def mean(l):
        return tuple(int(sum(c[i] for c in l) / len(l)) for i in range(3))
    k = max(1, len(px) // 3)
    base, dark, light = mean(px), mean(px[:k]), mean(px[-k:])
    sat = sorted(px, key=lambda p: -(max(p) - min(p)))
    top = sat[:max(1, len(px) // 10)]
    acc = mean(top) if (max(top[0]) - min(top[0])) > 40 else light
    for word, tint in TINT.items():
        if word in name and max(base) - min(base) < 30:            # grey textures the game tints green
            lum = sum(base) / 3 / 255.0
            s = lambda c: tuple(int(min(255, 255 * v * (0.55 + lum))) for v in c)
            base, dark, light, acc = s(tint), s((tint[0] * .7, tint[1] * .7, tint[2] * .7)), s((tint[0] * 1.25, tint[1] * 1.2, tint[2] * 1.25)), s(tint)
    hx = lambda c: "%02x%02x%02x" % c
    rows.append("%s=%s%s,%s,%s,%s" % (name, "b" if d == "blocks" else "i", hx(base), hx(dark), hx(light), hx(acc)))
body = ";".join(sorted(rows))
out = ["# ============================================================ vanilla item colours (generated by tools_make_palette.py)",
       "# name=kind + average, dark, light and accent colour measured from the game's textures (kind: b block, i item).",
       "# Only these numbers are kept; the app draws its own simplified tiles from them.",
       "ICON_DATA = ("]
for i in range(0, len(body), 110):
    out.append('    "%s"' % body[i:i + 110])
out.append(")")
open("src/p2a_icons.py", "w").write("\n".join(out) + "\n")
print(len(rows), "items,", len(body) // 1024, "KB")
